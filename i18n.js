export function t(key, params) {
  const text = DICT[LANG][key] ?? DICT.de[key];
  if (text === undefined) {
    console.warn(`Missing translation: ${key}`);
    return key;
  }
  return params ? text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match)) : text;
}

